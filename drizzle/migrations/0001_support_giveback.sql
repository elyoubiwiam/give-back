ALTER TABLE public.profiles ADD COLUMN support_giveback boolean NOT NULL DEFAULT false;
CREATE OR REPLACE FUNCTION public.handle_new_user() RETURNS trigger LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $$
BEGIN
  INSERT INTO public.profiles (id, name, support_giveback) VALUES (
    NEW.id,
    COALESCE(NEW.raw_user_meta_data->>'name', NEW.raw_user_meta_data->>'full_name', ''),
    COALESCE((NEW.raw_user_meta_data->>'support_giveback')::boolean, false)
  );
  RETURN NEW;
END $$;